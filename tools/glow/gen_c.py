# Generates src/harness/glow_table.c from glow_table.json: python3 gen_c.py
import json, os
here = os.path.dirname(os.path.abspath(__file__))
table = json.load(open(os.path.join(here, 'glow_table.json')))
out = os.path.join(here, '..', '..', 'src', 'harness', 'glow_table.c')
entries = sorted(table.items(), key=lambda kv: kv[0].upper())
lines = ['// Generated by tools/glow/gen_c.py from tools/glow/glow_table.json - do not edit', '#include "glow_table.h"', '']
for n, (name, e) in enumerate(entries):
    if e.get('rects'):
        lines.append('static const short rects_%d[] = { %s };' % (n, ', '.join(str(v) for r in e['rects'] for v in r)))
lines.append('')
lines.append('const tGlow_entry gGlow_table[] = {')
for n, (name, e) in enumerate(entries):
    mask = [0] * 32
    for i in e['indices']:
        mask[i >> 3] |= 1 << (i & 7)
    rects = e.get('rects') or []
    lines.append('    { "%s", %.2ff, { %s }, %d, %s }, // %s: %s' % (
        name.upper(), e['intensity'], ', '.join('0x%02x' % b for b in mask), len(rects),
        ('rects_%d' % n) if rects else 'NULL', e['kind'], e.get('note', '').replace('*/', '')))
lines.append('};')
lines.append('const int gGlow_table_count = %d;' % len(entries))
open(out, 'w').write('\n'.join(lines) + '\n')
print('wrote', out, len(entries), 'entries')
